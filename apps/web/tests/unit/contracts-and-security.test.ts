import { describe, it, expect } from "vitest";

describe("Web Security and Invariant Tests", () => {
  it("never includes authentication credentials in public share URLs", () => {
    const rawToken = "a1b2c3d4e5f67890123456789abcdef0123456789abcdef0123456789abcdef0";
    const shareUrl = `https://medlab.app/share/${rawToken}`;

    expect(shareUrl).not.toContain("bearer");
    expect(shareUrl).not.toContain("authorization");
    expect(shareUrl).not.toContain("password");
    expect(shareUrl).toContain(`/share/${rawToken}`);
  });

  it("verifies mandatory non-diagnostic disclaimer content invariants", () => {
    const standardDisclaimer =
      "For informational and health literacy purposes only. This summary is generated by artificial intelligence and does not constitute medical advice, diagnosis, or treatment recommendations. Always consult a qualified healthcare provider.";

    expect(standardDisclaimer).toContain("not constitute medical advice");
    expect(standardDisclaimer).toContain("diagnosis");
    expect(standardDisclaimer).toContain("Always consult a qualified healthcare provider");
  });

  it("validates that retention countdown calculates correct days remaining", () => {
    const now = new Date();
    const purgeDate = new Date(now.getTime() + 25 * 24 * 60 * 60 * 1000); // 25 days later
    const diffDays = Math.ceil((purgeDate.getTime() - now.getTime()) / (1000 * 60 * 60 * 24));

    expect(diffDays).toBe(25);
    expect(diffDays).toBeGreaterThan(0);
    expect(diffDays).toBeLessThanOrEqual(30);
  });
});
